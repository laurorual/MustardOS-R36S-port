# C10: consume generated Buildroot profile files through the C09 RAM harness.
c10_ui_bound=0
c10_hotkeys_bound=0
c10_profile_bound=0
c06_before_core() {
    c10_c09_before_core || return 1
    sha256sum /etc/default/muos-ui /opt/muos/share/hotkey/r35s-bringup.json > "$state/profile-defaults-before.sha256" || return 1
    while IFS= read -r path; do
        case "$path" in
            opt/muos/device/config/*) destination=$state/device-config/${path#opt/muos/device/config/} ;;
            opt/muos/config/*) destination=$state/config/${path#opt/muos/config/} ;;
            *) continue ;;
        esac
        [ -d "$(dirname "$destination")" ] || return 1
        cat "$package/profile/overlay/$path" > "$destination" || return 1
    done < "$package/profile-files.txt"
    cat "$package/profile/overlay/etc/default/muos-core" > "$state/core.conf" || return 1
    cat "$package/profile/overlay/opt/muos/device/control/asound.state" > "$state/asound.state" || return 1
    mount --bind "$package/profile/overlay/etc/default/muos-ui" /etc/default/muos-ui || return 1
    c10_ui_bound=1
    mount --bind "$package/profile/overlay/opt/muos/share/hotkey/r35s-bringup.json" /opt/muos/share/hotkey/r35s-bringup.json || return 1
    c10_hotkeys_bound=1
    # Compare exact generated bytes before core/helpers legitimately rewrite
    # config values in muvarctl's canonical format (without trailing newline).
    c06_help_start || return 1
}
c06_help_start() {
    if [ "$c10_profile_bound" = 1 ]; then
        volume=$(/opt/muos/frontend/muvarctl get global settings/general/volume) || return 1
        brightness=$(/opt/muos/frontend/muvarctl get global settings/general/brightness) || return 1
        [ "$volume:$brightness" = 100:80 ] || return 1
        [ "$(cat /sys/class/backlight/backlight/brightness)" = 80 ] || return 1
        sha256sum -c "$package/profile-static.sha256" > "$state/profile-static.txt" 2>&1 || return 1
        printf 'RUNTIME_VOLUME=%s\nRUNTIME_BRIGHTNESS=%s\n' "$volume" "$brightness" > "$state/profile-runtime.txt"
        wc -c /opt/muos/config/settings/general/volume /opt/muos/config/settings/general/brightness >> "$state/profile-runtime.txt"
        echo C10_GENERATED_PROFILE_ACTIVE=1
        echo C06_NATIVE_CONFIRM_BACK=1
        echo C06_NAV_WAVE_ADJUSTED=1
        return 0
    fi
    for effect in navigate info_open info_close; do
        cp "$package/profile/overlay/opt/muos/share/theme/MustardOS/sound/$effect.wav" "$state/$effect.wav" || return 1
        mount --bind "$state/$effect.wav" "$c06_theme/$effect.wav" || return 1
        c06_sound_binds="$effect $c06_sound_binds"
    done
    # All generated files must be active before the temporary UI enable bind.
    sha256sum -c "$package/profile-effective.sha256" > "$state/profile-effective.txt" 2>&1 || return 1
    c10_profile_bound=1
    echo C10_GENERATED_PROFILE_ACTIVE=1
    echo C06_NATIVE_CONFIRM_BACK=1
    echo C06_NAV_WAVE_ADJUSTED=1
}
c09_restore() {
    c10_rc=0
    if [ "$c10_hotkeys_bound" = 1 ]; then
        if umount /opt/muos/share/hotkey/r35s-bringup.json; then c10_hotkeys_bound=0; else c10_rc=1; fi
    fi
    if [ "$c10_ui_bound" = 1 ]; then
        if umount /etc/default/muos-ui; then c10_ui_bound=0; else c10_rc=1; fi
    fi
    c10_c09_restore || c10_rc=1
    if [ -f "$state/profile-defaults-before.sha256" ]; then
        sha256sum -c "$state/profile-defaults-before.sha256" > "$state/profile-defaults-restored.txt" 2>&1 || c10_rc=1
    fi
    return "$c10_rc"
}
